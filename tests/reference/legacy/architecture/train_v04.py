def factor(examples,total=64000,warmup=640,decay_start=25000):
    if examples<warmup:return min(1.,(examples+32)/warmup)
    if examples<decay_start:return 1.
    x=min(1.,max(0.,(examples-decay_start)/max(1,total-decay_start)))
    return .1+.9*(1+math.cos(math.pi*x))/2


class OnlineTrainer(RefinementTrainer):
    def __init__(self,*args,online,**kwargs):
        super().__init__(*args,**kwargs);self.online=online

    def train_batch(self,rows):
        self.model.train();tensors=self.online.collate(rows)
        if not torch.isfinite(tensors[0]).all():raise FloatingPointError('Non-finite frozen features')
        self.optimizer.zero_grad(set_to_none=True)
        self.emit('before_forward',batch=tensors,rows=rows)
        with sweep.autocast(self.device):
            logits=self.model(*tensors[:4]).float()
            losses=-(tensors[4]*logits.log_softmax(-1)).sum(-1);loss=losses.mean()
        if not torch.isfinite(loss):raise FloatingPointError('Non-finite training loss')
        self.emit('after_forward',outputs=logits,targets=tensors[4],per_example_loss=losses,loss=loss,rows=rows)
        self.emit('before_backward',loss=loss);loss.backward();self.emit('after_backward',loss=loss)
        norm=torch.nn.utils.clip_grad_norm_(self.model.parameters(),1.,error_if_nonfinite=True)
        self.emit('before_optimizer_step');rates=[g['lr'] for g in self.optimizer.param_groups]
        self.optimizer.step();self.state['step']+=1;self.state['examples_seen']+=len(rows)
        self.scheduler.step();self.emit('after_optimizer_step')
        return {'loss':float(loss.detach()),'cross_entropy':float(loss.detach()),'gradient_norm':float(norm),
                'learning_rate':rates[0],'adamw_learning_rate':rates[-1],**self.model.diagnostics()}


def prepare(args,implementation):
    manifest=json.loads((args.data_dir/'manifest.json').read_text())
    audit=json.loads((args.data_dir/'audit.json').read_text())
    if (manifest['dataset'],manifest['version'])!=('groundbeef','0.4') or not audit['verified']:
        raise ValueError('Requires audited Groundbeef v0.4')
    for item in manifest['files']:
        if file_hash(args.data_dir/item['file'])!=item['sha256']:raise ValueError('Dataset changed: '+item['file'])
    identity={'checkpoint':implementation.CHECKPOINT,'revision':implementation.REVISION,
        'weight_sha256':implementation.WEIGHT_SHA256,'quantization':'bnb-nf4',
        'implementation_sha256':file_hash(args.kiln_model_dir/'model.py'),
        'tokenizer_sha256':file_hash(args.base_dir/'tokenizer.json'),
        'serialization_sha256':hashlib_serialization(),'dataset_manifest_sha256':file_hash(args.data_dir/'manifest.json'),
        'hidden_width':3840,'dtype':'bfloat16','tensor':'final-normalized-token-states-before-trainable-projection'}
    if identity['tokenizer_sha256']!=manifest['tokenizer_sha256']:raise ValueError('Tokenizer differs')
    path=args.output_dir/'selection.json'
    if path.exists():
        selection=json.loads(path.read_text())
        if selection['identity']!=identity:raise ValueError('Prepared selection identity changed')
    else:
        tokenizer=Tokenizer.from_file(str(args.base_dir/'tokenizer.json'));selection={'identity':identity,'splits':{}}
        counts={e['file'].split('.')[0]:e['rows'] for e in manifest['files']}
        for split in ['train','validation','calibration']:
            records=[]
            for raw in tqdm(read_rows(args.data_dir/(split+'.jsonl.gz')),total=counts[split],desc='Tokenize '+split,unit='row'):
                row=encode(raw,tokenizer,4096)
                if row is None:raise ValueError('Unexpected truncated request: '+raw['id'])
                row.update(category=raw['metadata']['category'],semantic_class=raw['metadata']['semantic_class'],
                    legacy=raw['metadata'].get('prior_validation_monitoring',False),
                    cache='features/'+digest([row['id'],row['ids'],row['positions']])+'.pt')
                records.append(row)
            if len(records)!=counts[split]:raise ValueError('Split count changed')
            selection['splits'][split]=records
        lookup={r['id']:r for r in selection['splits']['validation']}
        quick=[]
        for raw in read_rows(args.data_dir/'validation-quick.jsonl.gz'):
            actual=encode(raw,tokenizer,4096);row=lookup[raw['id']]
            if any(actual[k]!=row[k] for k in actual):raise ValueError('Quick panel differs')
            quick.append(row)
        selection['splits']['validation-quick']=quick
        if not args.plan_only:atomic_json(path,selection)
    return manifest,identity,selection


def score(logits,rows):
    if any(not torch.isfinite(v).all() for v in logits):raise FloatingPointError('Non-finite validation logits')
    result={**basic_metrics(logits,rows),**breakdown(logits,rows)}
    grouped=defaultdict(list)
    for v,r in zip(logits,rows):grouped[(r['dataset_source'],r['semantic_class'])].append((v,r))
    result['by_semantic_class']={s+'/'+c:basic_metrics([v for v,_ in rr],[r for _,r in rr]) for (s,c),rr in grouped.items()}
    return result


def run(args):
    args.output_dir.mkdir(parents=True,exist_ok=True)
    with (args.output_dir/'.run.lock').open('w') as lock:
        fcntl.flock(lock,fcntl.LOCK_EX|fcntl.LOCK_NB);execute(args)


def execute(args):
    torch.set_num_threads(8)
    implementation=load_kiln(args.kiln_model_dir)
    manifest,identity,selection=prepare(args,implementation)
    rows=selection['splits']['train'];batches=training_batches(rows,args.batch_size,args.token_budget,args.seed)
    root=Path(__file__).parents[1]
    inference_files=['readout_mixed.py','readout_refinement.py','readout_ablation.py','model.py','trainer.py','optimizers.py','train.py']
    code_files=['architecture/train_v04.py','gemma_decisions/online.py','gemma_decisions/validation_cache.py',
                'gemma_decisions/pilot.py','gemma_decisions/model.py','reasoning/model.py',
                'gemma_decisions/evaluation.py','gemma_decisions/sweep.py','gemma_decisions/tracking.py']
    config={'variant':'mixed-request-residual','dataset':'groundbeef-v0.4','feature_identity':identity,
        'seed':args.seed,'epochs':1,'examples':len(rows),'total_steps':len(batches),'width':1024,'head_type':'bigru',
        'attention_heads':4,'low_steps':2,'high_cycles':2,'gate_width':32,'adapter_rank':64,
        'batch_size':args.batch_size,'token_budget':args.token_budget,'backbone_batch_size':1,
        'validation_batch_size':args.validation_batch_size,'validation_token_budget':args.validation_token_budget,
        'lr':args.lr,'muon_lr':args.muon_lr,'weight_decay':.01,'beta2':.999,'gradient_clip':1.,
        'schedule':'sample-based warmup/steady/cosine cooldown','warmup_examples':640,'decay_start_examples':args.decay_start,
        'minimum_lr_factor':.1,'optimizer':'muon+adamw','loss':'unweighted native/teacher CE',
        'training_features_cached':False,'validation_features_cached':True,
        'quick_every_examples':args.quick_every,'full_every_examples':args.full_every,
        'save_every_examples':1000,'keep_best_checkpoints':3,'early_stop_patience':args.patience,
        'early_stop_min_examples':24000,'early_stop_min_delta':.002,
        'train_batch_order_sha256':digest([[r['id'] for r in b] for b in batches]),
        'source_sha256':{f:file_hash(root/'architecture'/f) for f in inference_files},
        'code_sha256':{f:file_hash(root/f) for f in code_files},
        'image_tag':args.image_tag,'image_id':args.image_id,'torch':str(torch.__version__),'cuda':torch.version.cuda,
        'initialization':'fresh decision/gate/adapter; tied pretrained letter readout; frozen original backbone',
        'checkpoint_selection':'fixed full 4.5K category macro CE; quick panel never selects or stops'}
    if args.plan_only:
        print(json.dumps({k:config[k] for k in ['dataset','examples','total_steps','batch_size','token_budget',
             'training_features_cached','validation_features_cached','decay_start_examples','quick_every_examples','full_every_examples']},indent=2));return
    config_path=args.output_dir/'experiment.json'
    if config_path.exists() and json.loads(config_path.read_text())!=config:raise ValueError('Experiment identity differs: use a new run directory')
    atomic_json(config_path,config)
    for rel in inference_files:
        dest=args.output_dir/'code_snapshot/architecture'/rel;dest.parent.mkdir(parents=True,exist_ok=True)
        if not dest.exists():dest.write_bytes((root/'architecture'/rel).read_bytes())
    for rel in code_files:
        dest=args.output_dir/'code_snapshot'/rel;dest.parent.mkdir(parents=True,exist_ok=True)
        if not dest.exists():dest.write_bytes((root/rel).read_bytes())
    logger=RunLog(args.output_dir/'logging',args.output_dir.name,config,args.overfit_url,'Bazza · Groundbeef v0.4')
    state={'step':0,'examples_seen':0,'epoch':0,'batch_cursor':0,'loss_sum':0.,'best_ce':float('inf'),'stale_full':0,
           'last_full_examples':-1,'last_quick_examples':-1}
    def status(phase,**extra):atomic_json(args.output_dir/'status.json',{'phase':phase,'updated_at':time.time(),
        'step':state['step'],'examples_seen':state['examples_seen'],'total_examples':len(rows),**extra})
    status('loading_backbone')
    backbone=implementation.load_model(args.base_dir,quantization='bnb-nf4').requires_grad_(False).eval()
    weight,readout=load_letters(args.base_dir,identity)
    torch.manual_seed(args.seed)
    model=MixedReadout(make_head(3840,1024,4,2,2,'bigru'),LetterReadout(weight,readout['softcap'])).cuda()
    optimizer=make_optimizer(model,'muon',args.lr,.01,.999,args.muon_lr,False)
    online=OnlineFeatures(backbone,'cuda',backbone_batch_size=1)
    scheduler=torch.optim.lr_scheduler.LambdaLR(optimizer,lambda step:factor(state['examples_seen'],len(rows),640,args.decay_start))
    trainer=OnlineTrainer(model,optimizer,scheduler,args.output_dir/'validation_cache',online=online)
    last=args.output_dir/'last.pt';retained=[]
    if (args.output_dir/'checkpoints.json').exists():retained=json.loads((args.output_dir/'checkpoints.json').read_text())['checkpoints']
    if last.exists():
        saved=torch.load(last,weights_only=True,map_location='cpu')
        if saved['config']!=config:raise ValueError('Resume checkpoint identity differs')
        model.load_state_dict(saved['head'],strict=True);optimizer.load_state_dict(saved['optimizer'])
        state.clear();state.update(saved['state']);scheduler.load_state_dict(saved['scheduler'])
        torch.set_rng_state(saved['rng']);torch.cuda.set_rng_state_all(saved['cuda_rng'])
        print(f'Resuming at {state["examples_seen"]:,} examples / update {state["step"]}',flush=True)
    trainer.state=state
    observations=TrainingMetrics();trainer.on('after_forward',observations.forward);trainer.on('batch_end',observations.batch)
    cache_identity={**identity,'torch':str(torch.__version__),'cuda':torch.version.cuda,'image_id':args.image_id,
                    'backbone_batch_size':1,'feature_dtype':'bfloat16'}
    cache=ValidationCache(args.output_dir/'validation_cache',cache_identity,selection['splits']['validation'])
    def save_checkpoint(path,validation=None):
        sweep.atomic_save({'head':model.state_dict(),'optimizer':optimizer.state_dict(),'scheduler':scheduler.state_dict(),
            'config':config,'readout':readout,'state':state.copy(),'rng':torch.get_rng_state(),
            'cuda_rng':torch.cuda.get_rng_state_all(),'validation_full':validation},path)
    def validation(panel):
        rr=selection['splits']['validation' if panel=='full' else 'validation-quick']
        save_checkpoint(last);status('caching_validation',panel=panel)
        cache.ensure(rr,online,logger,state['examples_seen'],status,progress=True)
        status('validating',panel=panel)
        values=cache.predict(model,rr,max_rows=args.validation_batch_size,token_budget=args.validation_token_budget,device='cuda',progress=True)
        report=score(values,rr);atomic_json(args.output_dir/f'validation-{panel}-step-{state["step"]}.json',report)
        metrics={f'validation/{panel}/{k}':report[k] for k in ['accuracy','cross_entropy','macro_category_cross_entropy']}
        for group in ['category','source','task','semantic_class']:
            key='by_dataset_source' if group=='source' else 'by_'+group
            for name,entry in report[key].items():
                for metric in ['accuracy','cross_entropy']:metrics[f'validation/{panel}/{group}/{name}/{metric}']=entry[metric]
        logger.log(metrics,state['examples_seen'])
        print(f'{panel} validation: accuracy={report["accuracy"]:.2%}, macro CE={report["macro_category_cross_entropy"]:.5f}',flush=True)
        state['last_'+panel+'_examples']=state['examples_seen']
        if panel=='full':
            ce=report['macro_category_cross_entropy']
            if ce<state['best_ce']-.002:state['best_ce']=ce;state['stale_full']=0
            else:state['stale_full']+=1
            filename=f'checkpoint-step-{state["step"]}.pt';candidate={'file':filename,'step':state['step'],
                'examples_seen':state['examples_seen'],'accuracy':report['accuracy'],'macro_category_cross_entropy':ce}
            top=sorted(retained+[candidate],key=lambda e:(e['macro_category_cross_entropy'],-e['accuracy'],e['step']))[:3]
            if candidate in top:
                save_checkpoint(args.output_dir/filename,report);candidate['sha256']=file_hash(args.output_dir/filename)
            for e in retained:
                if e not in top:(args.output_dir/e['file']).unlink()
            retained[:]=top;atomic_json(args.output_dir/'checkpoints.json',{'selection':'full category macro CE','checkpoints':retained})
        save_checkpoint(last,report if panel=='full' else None)
        return report
    result=None;phase='completed';started=time.perf_counter()
    try:
        status('training')
        print(f'Fresh Bazza v0.4: {len(rows):,} examples, one pass. Training features are computed online, not exported.',flush=True)
        progress=tqdm(total=len(rows),initial=state['examples_seen'],desc='Bazza v0.4',unit='example')
        for i in range(state['batch_cursor'],len(batches)):
            if sweep.STOP_REQUESTED:phase='stopped';break
            batch=batches[i];before=state['examples_seen'];trainer.emit('batch_start',rows=batch)
            metrics=trainer.train_batch(batch);state['batch_cursor']=i+1;state['loss_sum']+=metrics['loss']*len(batch)
            trainer.emit('batch_end',metrics=metrics)
            progress.update(len(batch));progress.set_postfix(loss=f'{metrics["loss"]:.4f}',muon=f'{metrics["learning_rate"]:.2g}',adam=f'{metrics["adamw_learning_rate"]:.2g}')
            if state['step']%10==0:
                logger.log({**{'train/'+k:v for k,v in metrics.items()},'train/epoch_running_loss':state['loss_sum']/state['examples_seen'],
                    'train/examples_seen':state['examples_seen'],'train/optimizer_steps':state['step'],
                    'train/examples_per_second_this_session':(state['examples_seen']-progress.initial)/max(time.perf_counter()-started,1e-6)},state['examples_seen'])
                status('training')
            if state['examples_seen']//1000>before//1000:save_checkpoint(last)
            due=validation_due(state['examples_seen'],len(batch),args.quick_every,args.full_every,final=i+1==len(batches))
            if due:
                result=validation(due)
                if due=='full' and state['examples_seen']>=24000 and state['stale_full']>=args.patience:
                    phase='early_stopped';break
                status('training')
        progress.close()
        if phase=='completed':state['completed_epochs']=1
        save_checkpoint(last,result if state['last_full_examples']==state['examples_seen'] else None)
        if observations.rows:atomic_json(args.output_dir/'training-summary.json',observations.report())
        status(phase,retained_best=retained);logger.finish('completed' if phase in ['completed','early_stopped'] else 'stopped')
        print(f'Run {phase}. Best retained full-validation checkpoints: '+json.dumps(retained),flush=True)
    except sweep.SweepStopped:
        save_checkpoint(last);status('stopped',retained_best=retained);logger.finish('stopped')
    except BaseException as error:
        # An optimizer/runtime exception can leave a partially updated batch.
        # Preserve the most recent successfully committed state for restart.
        status('failed',error=str(error),traceback=traceback.format_exc(),resume_from='last.pt');logger.finish('failed');raise


def main():
    p=argparse.ArgumentParser(description=__doc__)
    for name in ['data-dir','output-dir','base-dir','kiln-model-dir']:p.add_argument('--'+name,type=Path,required=True)
    for name in ['image-tag','image-id']:p.add_argument('--'+name,required=True)
    p.add_argument('--seed',type=int,default=20261013);p.add_argument('--batch-size',type=int,default=32)
    p.add_argument('--token-budget',type=int,default=32768);p.add_argument('--lr',type=float,default=3e-5)
    p.add_argument('--validation-batch-size',type=int,default=64);p.add_argument('--validation-token-budget',type=int,default=65536)
    p.add_argument('--muon-lr',type=float,default=.003);p.add_argument('--decay-start',type=int,default=25000)
    p.add_argument('--quick-every',type=int,default=4000);p.add_argument('--full-every',type=int,default=8000)
    p.add_argument('--patience',type=int,default=3);p.add_argument('--plan-only',action='store_true')
    p.add_argument('--overfit-url',default='http://127.0.0.1:6006')
    a=p.parse_args()
    if a.batch_size<1 or a.token_budget<4096 or a.validation_batch_size<1 or a.validation_token_budget<4096 or a.quick_every<1 or a.full_every<1 or a.full_every%a.quick_every or a.patience<1:p.error('Invalid batching/validation settings')
    signal.signal(signal.SIGINT,sweep.request_stop);signal.signal(signal.SIGTERM,sweep.request_stop)
    run(a)


if __name__=='__main__':main()
